// Quick demo-mode walkthrough in headless Chromium against server.mjs on a test port; writes screenshots to evidence/smoke/.
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';
import { spawn } from 'node:child_process';
import { mkdir } from 'node:fs/promises';
import path from 'node:path';
const LAB = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PORT = 4339, out = path.join(LAB, 'evidence/smoke');
await mkdir(out, { recursive: true });
const server = spawn(process.execPath, ['server.mjs', `--port=${PORT}`], { cwd: LAB, stdio: ['ignore', 'pipe', 'pipe'] });
server.stdout.on('data', d => process.stdout.write(`[server] ${d}`)); server.stderr.on('data', d => process.stderr.write(`[server] ${d}`));
await new Promise(r => setTimeout(r, 600));
const browser = await chromium.launch({ headless: true });
const errors = [];
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
  page.on('pageerror', e => errors.push(e.message)); page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
  await page.goto(`http://127.0.0.1:${PORT}/?mode=research&demo=1&blocks=B1&tester=smoke&diag=14`);
  await page.screenshot({ path: `${out}/01-setup.png` });
  await page.getByRole('button', { name: 'Start demo' }).click();
  await page.getByRole('button', { name: 'Begin' }).waitFor();
  await page.waitForTimeout(800);
  await page.screenshot({ path: `${out}/02-setup-camera-on.png` });
  await page.getByRole('button', { name: 'Begin' }).click();
  await page.getByRole('heading', { name: 'Calibrate' }).waitFor();
  await page.screenshot({ path: `${out}/03-calibrate.png` });
  await page.keyboard.press('Space');
  await page.locator('.calibration-point').waitFor({ timeout: 10000 });
  await page.waitForTimeout(2500);
  await page.screenshot({ path: `${out}/04-calibration-dot.png` });
  await page.getByRole('heading', { name: 'Calibrate head movement' }).waitFor({ timeout: 90000 });
  await page.screenshot({ path: `${out}/05-head-ready.png` });
  await page.keyboard.press('Space');
  await page.getByRole('heading', { name: 'Neutral' }).waitFor({ timeout: 90000 });
  await page.waitForTimeout(500);
  await page.screenshot({ path: `${out}/06-instruction.png` });
  await page.keyboard.press('Space');
  await page.locator('.validation-dot').waitFor();
  await page.waitForTimeout(1500);
  await page.screenshot({ path: `${out}/07-block-dot.png` });
  await page.keyboard.press('Escape');
  await page.getByRole('heading', { name: 'Paused' }).waitFor();
  await page.screenshot({ path: `${out}/08-paused.png` });
  await page.keyboard.press('Space');
  await page.getByRole('heading', { name: 'Results' }).waitFor({ timeout: 120000 });
  await page.waitForTimeout(500);
  await page.screenshot({ path: `${out}/09-summary.png`, fullPage: true });
  console.log('smoke done; errors:', errors);
} catch (e) { console.error('smoke failed:', e.message, errors); try { const page = browser.contexts()[0]?.pages()[0]; if (page) { await page.screenshot({ path: `${out}/failure.png` }); console.error('page text:', (await page.locator('body').innerText()).slice(0, 300)); } } catch {} process.exitCode = 1; }
finally { await browser.close(); server.kill(); }
